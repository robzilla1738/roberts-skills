def md_finding(f):
    sev_conf = f"[{f['severity']}-{f['confidenceLabel']}]"
    lines = [f"### {sev_conf} {f['title']}",
             f"- **ID:** {f['id']}",
             f"- **Location:** {f['location']['file']}:{f['location']['startLine']}",
             f"- **Lens:** {f['lens']}",
             f"- **Severity:** {f['severity']}",
             f"- **Confidence:** {f['confidenceLabel']}"]
    if f.get("impactClass") and f["impactClass"] != "correctness":
        lines.append(f"- **Impact class:** {f['impactClass']}")
    lines += [f"- **Trigger:** {f['trigger']}",
              f"- **Trace:** {f['trace']}",
              f"- **Impact:** {f['impact']}",
              f"- **Repro:** {f.get('repro') or 'not reproduced: static finding'}",
              f"- **Fix sketch:** {f.get('fixSketch') or '—'}"]
    if f.get("alsoFlaggedBy"):
        also = ", ".join(f"{x['lens']} (line {x['line']})" for x in f["alsoFlaggedBy"])
        lines.append(f"- **Also flagged by:** {also} — cross-lens convergence")
    if (f.get("verified") or {}).get("verdict"):
        v = f["verified"]
        note = f" — {v['note']}" if v.get("note") else ""
        lines.append(f"- **Verified:** {v['verdict']} (via {v.get('by', 'verify')}){note}")
    lines.append(f"- **Fingerprint:** `{f['fingerprint']}`")
    return "\n".join(lines)


