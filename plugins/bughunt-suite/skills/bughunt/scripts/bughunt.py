MARKER_RE = re.compile(r"\b(TODO|FIXME|HACK|XXX)\b[:\s]?(.{0,120})")
FLAG_RE = re.compile(
    r"(feature[_-]?flag|featureFlag|FeatureFlag|flags?\.[A-Za-z_][\w]*|"
    r"isEnabled\(|is_enabled\(|\.enabled\b|toggle[s]?\.[A-Za-z_])")
ENV_KEY_RE = re.compile(r"^\s*(?:export\s+)?([A-Z][A-Z0-9_]+)\s*=", re.M)


def blame_age_days(root, rel, line_no):
    out = run_git(root, ["blame", "-L", f"{line_no},{line_no}", "--line-porcelain", "--", rel])
    if not out:
        return None, None
    author, ts = None, None
    for ln in out.splitlines():
        if ln.startswith("author "):
            author = ln[7:]
        elif ln.startswith("author-time "):
            ts = int(ln.split()[1])
    if ts is None:
        return None, author
    days = (datetime.now(timezone.utc).timestamp() - ts) / 86400
    return round(days), author


def cmd_signals(args):
    root = Path(args.root).resolve()
    use_git = git_available(root)
    todos, flags, config_drift, long_scripts = [], [], [], []
    blames_left = 400  # hard cap so huge repos stay fast

    for p, rel in iter_files(root, args.exclude):
        lang = LANG_BY_EXT.get(p.suffix.lower())
        if not lang:
            continue
        text = read_text(p)
        if text is None:
            continue
        first = "\n".join(text.splitlines()[:5])
        generated, vendored, _ = detect_flags(rel, text, first)
        if generated or vendored:
            continue
        for i, line in enumerate(text.splitlines(), 1):
            m = MARKER_RE.search(line)
            if m and lang in CODE_LANGS:
                age, author = (None, None)
                if use_git and blames_left > 0:
                    age, author = blame_age_days(root, rel, i)
                    blames_left -= 1
                todos.append({"file": rel, "line": i, "kind": m.group(1),
                              "text": m.group(2).strip(), "ageDays": age, "author": author,
                              "aged": bool(age and age >= args.max_age_days)})
            fm = FLAG_RE.search(line)
            if fm and lang in CODE_LANGS:
                flags.append({"file": rel, "line": i, "ref": fm.group(0)})
        if lang == "shell" and text.count("\n") > 300:
            long_scripts.append({"path": rel, "kind": "shell",
                                 "note": f"{text.count(chr(10))} lines; consider splitting or profiling"})

    # config drift: .env.example vs .env / .env.local
    example = root / ".env.example"
    if example.exists():
        ex_keys = set(ENV_KEY_RE.findall(example.read_text(errors="replace")))
        for actual_name in (".env", ".env.local"):
            actual = root / actual_name
            if actual.exists():
                ac_keys = set(ENV_KEY_RE.findall(actual.read_text(errors="replace")))
                for k in sorted(ex_keys - ac_keys):
                    config_drift.append({"file": actual_name, "key": k,
                                         "note": "declared in .env.example but missing here"})
                for k in sorted(ac_keys - ex_keys):
                    config_drift.append({"file": ".env.example", "key": k,
                                         "note": f"present in {actual_name} but undocumented in .env.example"})

    # package.json scripts that chain many commands serially
    pkg = root / "package.json"
    if pkg.exists():
        try:
            scripts = json.loads(pkg.read_text(errors="replace")).get("scripts", {})
            for name, body in scripts.items():
                if isinstance(body, str) and body.count("&&") >= 3:
                    long_scripts.append({"path": f"package.json#scripts.{name}", "kind": "npm-script",
                                         "note": f"chains {body.count('&&') + 1} serial commands"})
        except (json.JSONDecodeError, OSError):
            pass

    flags = flags[:300]
    emit({"gitAvailable": use_git, "maxAgeDays": args.max_age_days,
          "todos": todos, "flags": flags, "configDrift": config_drift,
          "longScripts": long_scripts})


