LITERAL_RE = re.compile(r"\"[^\"]*\"|'[^']*'|`[^`]*`|\b\d[\d_.xa-fA-F]*\b")


def normalize_snippet(lines):
    joined = " ".join(ln.strip() for ln in lines if ln.strip())
    joined = LITERAL_RE.sub("§", joined)
    return re.sub(r"\s+", " ", joined).strip()


def fingerprint(root, finding):
    lens = finding["lens"]
    rel = finding["location"]["file"]
    start = finding["location"]["startLine"]
    end = finding["location"].get("endLine", start)
    snippet = None
    path = Path(root) / rel
    text = read_text(path) if path.exists() else None
    if text is not None:
        lines = text.splitlines()[start - 1:end]
        if lines:
            snippet = normalize_snippet(lines)
    basis = snippet if snippet else finding["title"]
    digest = hashlib.sha256(f"{lens}\x00{rel}\x00{basis}".encode()).hexdigest()
    return digest[:16]


def validate_finding(f, idx, errors):
    """Executable version of schema/finding.schema.json. Returns cleaned finding or None."""
    where = f"finding[{idx}]"
    if not isinstance(f, dict):
        errors.append(f"{where}: not an object")
        return None
    required = ["title", "lens", "severity", "confidence", "location", "trigger", "trace", "impact"]
    missing = [k for k in required if k not in f or f[k] in (None, "")]
    if missing:
        errors.append(f"{where} ({f.get('title', '?')}): missing {', '.join(missing)}")
        return None
    if f["lens"] not in LENSES:
        errors.append(f"{where}: unknown lens '{f['lens']}'")
        return None
    if f["severity"] not in SEVERITIES:
        errors.append(f"{where}: invalid severity '{f['severity']}'")
        return None
    try:
        conf = float(f["confidence"])
    except (TypeError, ValueError):
        errors.append(f"{where}: confidence not a number")
        return None
    if not 0.0 <= conf <= 1.0:
        errors.append(f"{where}: confidence {conf} out of [0,1]")
        return None
    f["confidence"] = conf
    loc = f["location"]
    if not isinstance(loc, dict) or "file" not in loc or "startLine" not in loc:
        errors.append(f"{where}: location needs file + startLine")
        return None
    try:
        loc["startLine"] = int(loc["startLine"])
        loc["endLine"] = int(loc.get("endLine", loc["startLine"]))
    except (TypeError, ValueError):
        errors.append(f"{where}: location lines not integers")
        return None
    if f.get("impactClass") and f["impactClass"] not in IMPACT_CLASSES:
        errors.append(f"{where}: invalid impactClass '{f['impactClass']}' (defaulted)")
        f["impactClass"] = None
    if f.get("verified") and f["verified"].get("verdict") not in VERDICTS:
        errors.append(f"{where}: invalid verified.verdict (cleared)")
        f["verified"] = None
    return f


def confidence_label(conf):
    return "Confirmed" if conf >= 0.85 else ("Probable" if conf >= 0.5 else "Speculative")


def overlaps(a, b, slack=5):
    a1, a2 = a["location"]["startLine"], a["location"].get("endLine", a["location"]["startLine"])
    b1, b2 = b["location"]["startLine"], b["location"].get("endLine", b["location"]["startLine"])
    return a["location"]["file"] == b["location"]["file"] and a1 <= b2 + slack and b1 <= a2 + slack


def cross_lens_cluster(findings, enabled, slack=1):
    """Collapse the SAME bug reported by different lenses at overlapping lines into one
    primary finding (+ alsoFlaggedBy), boosting confidence for the convergence. Same-lens
    findings are never merged (fingerprint dedupe already handled exact repeats). When
    disabled, fall back to the legacy behavior: boost confidence on overlap, keep all."""
    if not enabled:
        for i, a in enumerate(findings):
            for b in findings[i + 1:]:
                if a["lens"] != b["lens"] and overlaps(a, b, slack):
                    for x in (a, b):
                        if "cross-validated" not in (x.get("tags") or []):
                            x["confidence"] = min(0.99, x["confidence"] + 0.15)
                            x["confidenceLabel"] = confidence_label(x["confidence"])
                            x.setdefault("tags", []).append("cross-validated")
        return findings

    # Union-find over cross-lens overlap edges only (distinct lenses + overlapping lines).
    parent = list(range(len(findings)))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    for i, a in enumerate(findings):
        for j in range(i + 1, len(findings)):
            b = findings[j]
            if a["lens"] != b["lens"] and overlaps(a, b, slack):
                parent[find(i)] = find(j)

    groups = {}
    for i in range(len(findings)):
        groups.setdefault(find(i), []).append(findings[i])

    sev_rank = {s: i for i, s in enumerate(SEVERITIES)}
    out = []
    for members in groups.values():
        if len(members) == 1:
            out.append(members[0])
            continue
        primary = min(members, key=lambda x: (sev_rank[x["severity"]], -x["confidence"],
                                              -len(x.get("trace", ""))))
        others = [x for x in members if x is not primary]
        lenses = {x["lens"] for x in members}
        if len(lenses) > 1:  # genuine cross-lens convergence is strong signal
            primary["confidence"] = min(0.99, primary["confidence"] + 0.1 * len(others))
            primary["confidenceLabel"] = confidence_label(primary["confidence"])
            primary.setdefault("tags", [])
            if "cross-validated" not in primary["tags"]:
                primary["tags"].append("cross-validated")
        primary["alsoFlaggedBy"] = [
            {"lens": x["lens"], "title": x["title"], "severity": x["severity"],
             "confidence": round(x["confidence"], 2),
             "line": x["location"]["startLine"]} for x in others]
        out.append(primary)
    return out


def load_json_file(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, json.JSONDecodeError) as e:
        die(f"cannot read {path}: {e}")


def cmd_merge(args):
    root = Path(args.root).resolve()
    docs = []
    for src in args.inputs:
        if src == "-":
            try:
                docs.append(json.load(sys.stdin))
            except json.JSONDecodeError as e:
                die(f"stdin is not valid JSON: {e}")
        else:
            docs.append(load_json_file(src))

    run_meta, raw = None, []
    for doc in docs:
        if isinstance(doc, list):  # tolerate a bare findings array
            raw.extend(doc)
            continue
        if run_meta is None and doc.get("run"):
            run_meta = doc["run"]
        raw.extend(doc.get("findings", []))

    errors = []
    findings = [v for i, f in enumerate(raw) if (v := validate_finding(f, i, errors))]
    n_dropped = len(raw) - len(findings)
    for e in errors:
        log(f"  invalid: {e}", args.quiet)

    # normalize + fingerprint
    for f in findings:
        f.setdefault("impactClass", None)
        f["impactClass"] = f["impactClass"] or "correctness"
        if not re.fullmatch(r"[0-9a-f]{16}", str(f.get("fingerprint") or "")):
            f["fingerprint"] = fingerprint(root, f)
        f["confidenceLabel"] = confidence_label(f["confidence"])

    # quarantine refuted
    refuted = [f for f in findings if (f.get("verified") or {}).get("verdict") == "refuted"]
    refuted_ids = {id(f) for f in refuted}
    findings = [f for f in findings if id(f) not in refuted_ids]

    # dedupe identical fingerprints (same lens + site)
    by_fp = {}
    for f in findings:
        prev = by_fp.get(f["fingerprint"])
        if prev is None:
            by_fp[f["fingerprint"]] = f
        else:  # keep the clearer write-up: higher confidence, then longer trace
            keep = max(prev, f, key=lambda x: (x["confidence"], len(x.get("trace", ""))))
            by_fp[f["fingerprint"]] = keep
    findings = list(by_fp.values())
    n_before_cluster = len(findings)

    # cross-lens clustering: the same bug seen by multiple lenses collapses to one primary
    # finding (+ alsoFlaggedBy), with a confidence boost for the convergence.
    findings = cross_lens_cluster(findings, enabled=not args.no_cluster)
    n_clustered = n_before_cluster - len(findings)

    # suppressions
    sup_path = Path(args.suppress) if args.suppress else root / STATE_DIR / "suppressions.json"
    suppressed_fps = {}
    if sup_path.exists():
        sup_doc = load_json_file(sup_path)
        for entry in sup_doc.get("suppressions", []):
            suppressed_fps[entry.get("fingerprint")] = entry.get("reason", "")
    n_suppressed = 0
    for f in findings:
        f["suppressed"] = f["fingerprint"] in suppressed_fps
        if f["suppressed"]:
            f["suppressedReason"] = suppressed_fps[f["fingerprint"]]
            n_suppressed += 1

    # baseline diff
    base_path = Path(args.baseline) if args.baseline else root / STATE_DIR / "baseline.json"
    baseline_fps = {}
    if base_path.exists():
        base_doc = load_json_file(base_path)
        baseline_fps = {e["fingerprint"]: e for e in base_doc.get("findings", [])}
    fixed = []
    current_fps = {f["fingerprint"] for f in findings}
    for f in findings:
        f["baselineStatus"] = "existing" if f["fingerprint"] in baseline_fps else "new"
    if baseline_fps:
        fixed = [{"fingerprint": fp, "id": e.get("id"), "title": e.get("title"),
                  "lens": e.get("lens"), "severity": e.get("severity"),
                  "file": e.get("file")} for fp, e in baseline_fps.items()
                 if fp not in current_fps]

    # stable order + renumber ids
    sev_rank = {s: i for i, s in enumerate(SEVERITIES)}
    findings.sort(key=lambda f: (sev_rank[f["severity"]], -f["confidence"], f["location"]["file"]))
    for i, f in enumerate(findings, 1):
        f["id"] = f"BH-{i:03d}"

    new_active = [f for f in findings if f["baselineStatus"] == "new" and not f["suppressed"]]
    n_new_crit = sum(1 for f in new_active if f["severity"] in ("Critical", "High"))
    n_new_other = len(new_active) - n_new_crit

    out = {
        "schemaVersion": SCHEMA_VERSION,
        "tool": {"name": TOOL_NAME, "version": TOOL_VERSION},
        "run": run_meta or {"root": str(root), "commit": git_commit(root),
                            "finishedAt": now_iso()},
        "findings": findings,
        "refuted": refuted,
        "baselineDiff": {
            "baselinePresent": bool(baseline_fps),
            "new": [f["id"] for f in findings if f["baselineStatus"] == "new"],
            "existing": [f["id"] for f in findings if f["baselineStatus"] == "existing"],
            "fixed": fixed,
        },
        "summary": {
            "total": len(findings),
            "bySeverity": {s: sum(1 for f in findings if f["severity"] == s) for s in SEVERITIES},
            "byImpactClass": {c: n for c in IMPACT_CLASSES
                              if (n := sum(1 for f in findings if f["impactClass"] == c))},
            "new": len([f for f in findings if f["baselineStatus"] == "new"]),
            "fixed": len(fixed),
            "suppressed": n_suppressed,
            "refuted": len(refuted),
            "clustered": n_clustered,
            "invalidDropped": n_dropped,
        },
    }

    out_path = Path(args.out) if args.out else root / STATE_DIR / "findings.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    if args.write_baseline:
        base_entries = [{"fingerprint": f["fingerprint"], "id": f["id"], "title": f["title"],
                         "lens": f["lens"], "severity": f["severity"],
                         "file": f["location"]["file"]} for f in findings]
        base_path.parent.mkdir(parents=True, exist_ok=True)
        base_path.write_text(json.dumps(
            {"schemaVersion": SCHEMA_VERSION, "writtenAt": now_iso(),
             "findings": base_entries}, indent=2) + "\n", encoding="utf-8")

    s = out["summary"]
    log(f"{s['total']} total, {s['new']} new, {s['fixed']} fixed, "
        f"{s['suppressed']} suppressed, {s['refuted']} refuted "
        f"({n_new_crit} new critical/high) -> {out_path}", args.quiet)
    emit(out)

    if args.fail_on == "none":
        sys.exit(0)
    if n_new_crit and args.fail_on in ("critical-high", "any"):
        sys.exit(1)
    if n_new_other and args.fail_on == "any":
        sys.exit(2)
    if n_new_other and args.fail_on == "critical-high":
        sys.exit(2)
    sys.exit(0)


