# Side-effect tokens that disqualify a function from the "pure" shortlist.
IMPURE_PY = re.compile(
    r"\b(open|print|input|requests|urllib|subprocess|os\.|sys\.|random|"
    r"datetime\.now|time\.|global |nonlocal |self\.|cls\.|\.write|\.save|"
    r"db\.|session\.|cursor|logging)\b")
IMPURE_JS = re.compile(
    r"\b(fetch|console\.|document\.|window\.|process\.|require\(|fs\.|"
    r"this\.|await |Math\.random|Date\.|localStorage|axios|setTimeout|setInterval)\b")

PY_DEF = re.compile(r"^def\s+([A-Za-z_]\w*)\s*\(([^)]*)\)", re.M)
JS_FUNC = re.compile(
    r"^(?:export\s+)?(?:function\s+([A-Za-z_$][\w$]*)\s*\(([^)]*)\)|"
    r"(?:const|let)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:\(([^)]*)\)|[\w$]+)\s*=>)", re.M)


def detect_flags(rel, text, first_lines):
    generated = bool(GENERATED_PATH.search(rel)) or bool(GENERATED_MARKERS.search(first_lines))
    vendored = bool(VENDORED_PATH.search(rel))
    tests = bool(TEST_PATH.search(rel))
    return generated, vendored, tests


def find_functions(rel, lang, text):
    """Heuristic shortlist of pure-function candidates for /fuzz."""
    out = []
    lines = text.splitlines()
    if lang == "python":
        matches = list(PY_DEF.finditer(text))
        for i, m in enumerate(matches):
            start = text.count("\n", 0, m.start()) + 1
            end_off = matches[i + 1].start() if i + 1 < len(matches) else len(text)
            body = text[m.start():end_off]
            out.append({
                "file": rel, "name": m.group(1), "startLine": start,
                "endLine": start + body.count("\n"),
                "params": [p.strip().split(":")[0].split("=")[0].strip()
                           for p in m.group(2).split(",") if p.strip()],
                "pure_guess": not IMPURE_PY.search(body),
            })
    elif lang in ("javascript", "typescript"):
        for m in JS_FUNC.finditer(text):
            name = m.group(1) or m.group(3)
            params = m.group(2) if m.group(2) is not None else (m.group(4) or "")
            start = text.count("\n", 0, m.start()) + 1
            end = min(start + 60, len(lines))  # rough body window
            body = "\n".join(lines[start - 1:end])
            out.append({
                "file": rel, "name": name, "startLine": start, "endLine": end,
                "params": [p.strip().split(":")[0].split("=")[0].strip()
                           for p in params.split(",") if p.strip()],
                "pure_guess": not IMPURE_JS.search(body),
            })
    return out


def cmd_census(args):
    root = Path(args.root).resolve()
    files, languages, functions = [], {}, []
    totals = {"files": 0, "loc": 0, "bytes": 0, "codeFiles": 0, "testFiles": 0}
    for p, rel in iter_files(root, args.exclude):
        ext = p.suffix.lower()
        lang = LANG_BY_EXT.get(ext)
        try:
            size = p.stat().st_size
        except OSError:
            continue
        entry = {"path": rel, "lang": lang, "bytes": size, "loc": 0,
                 "generated": False, "vendored": False, "tests": False}
        if lang:
            text = read_text(p)
            if text is not None:
                entry["loc"] = text.count("\n") + (1 if text and not text.endswith("\n") else 0)
                first = "\n".join(text.splitlines()[:5])
                entry["generated"], entry["vendored"], entry["tests"] = detect_flags(rel, text, first)
                if (args.functions and lang in ("python", "javascript", "typescript")
                        and not entry["generated"] and not entry["vendored"] and not entry["tests"]):
                    functions.extend(find_functions(rel, lang, text))
            lstat = languages.setdefault(lang, {"files": 0, "loc": 0})
            lstat["files"] += 1
            lstat["loc"] += entry["loc"]
            if lang in CODE_LANGS:
                totals["codeFiles"] += 1
            if entry["tests"]:
                totals["testFiles"] += 1
        totals["files"] += 1
        totals["loc"] += entry["loc"]
        totals["bytes"] += size
        files.append(entry)
    out = {"root": str(root), "commit": git_commit(root), "files": files,
           "languages": languages, "totals": totals}
    if args.functions:
        out["functions"] = [f for f in functions if f["pure_guess"]] or functions[:50]
    emit(out)


