def cmd_diff(args):
    a = load_json_file(args.a)
    b = load_json_file(args.b)
    fa = {f["fingerprint"]: f for f in a.get("findings", []) if f.get("fingerprint")}
    fb = {f["fingerprint"]: f for f in b.get("findings", []) if f.get("fingerprint")}
    new = [fb[fp].get("id") or fp for fp in fb.keys() - fa.keys()]
    fixed = [fa[fp].get("id") or fp for fp in fa.keys() - fb.keys()]
    unchanged = [fb[fp].get("id") or fp for fp in fa.keys() & fb.keys()]
    emit({"new": sorted(new), "fixed": sorted(fixed), "unchanged": sorted(unchanged),
          "counts": {"new": len(new), "fixed": len(fixed), "unchanged": len(unchanged)}})


