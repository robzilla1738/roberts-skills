def render_sarif(doc):
    findings = [f for f in doc.get("findings", []) if not f.get("suppressed")]
    level = {"Critical": "error", "High": "error", "Medium": "warning", "Low": "note"}
    rules, seen = [], set()
    for f in findings:
        rule_id = f"bughunt/{f['lens']}"
        if rule_id not in seen:
            seen.add(rule_id)
            rules.append({
                "id": rule_id,
                "name": f["lens"],
                "shortDescription": {"text": f"bughunt {f['lens']} lens"},
                "helpUri": "https://github.com/robzilla1738/roberts-skills/tree/main/plugins/bughunt-suite",
            })
    results = [{
        "ruleId": f"bughunt/{f['lens']}",
        "level": level[f["severity"]],
        "message": {"text": f"{f['title']} — {f['impact']} (trigger: {f['trigger']})"},
        "locations": [{
            "physicalLocation": {
                "artifactLocation": {"uri": f["location"]["file"]},
                "region": {"startLine": f["location"]["startLine"],
                           "endLine": f["location"].get("endLine", f["location"]["startLine"])},
            }
        }],
        "partialFingerprints": {"bughuntFingerprint/v1": f["fingerprint"]},
        "properties": {"severity": f["severity"], "confidence": f["confidence"],
                       "impactClass": f.get("impactClass"), "id": f["id"]},
    } for f in findings]
    return {
        "$schema": "https://raw.githubusercontent.com/oasis-tcs/sarif-spec/master/Schemata/sarif-schema-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {"driver": {
                "name": TOOL_NAME, "version": TOOL_VERSION,
                "informationUri": "https://github.com/robzilla1738/roberts-skills/tree/main/plugins/bughunt-suite",
                "rules": rules,
            }},
            "results": results,
        }],
    }


def cmd_render(args):
    doc = json.load(sys.stdin) if args.input == "-" else load_json_file(args.input)
    root = Path(args.root).resolve()
    formats = [f.strip() for f in args.formats.split(",") if f.strip()]
    state = root / STATE_DIR
    state.mkdir(parents=True, exist_ok=True)
    written = []
    if "md" in formats:
        path = Path(args.md) if args.md else state / "report.md"
        path.write_text(render_md(doc), encoding="utf-8")
        written.append(str(path))
    if "html" in formats:
        path = Path(args.html) if args.html else state / "report.html"
        path.write_text(render_html(doc), encoding="utf-8")
        written.append(str(path))
    if "sarif" in formats:
        path = Path(args.sarif) if args.sarif else state / "report.sarif"
        path.write_text(json.dumps(render_sarif(doc), indent=2) + "\n", encoding="utf-8")
        written.append(str(path))
    log("wrote " + ", ".join(written), args.quiet)
    emit({"written": written})


