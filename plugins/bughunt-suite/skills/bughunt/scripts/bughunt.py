WEIGHTS = {"churn": 0.30, "complexity": 0.25, "recency": 0.15, "boundary": 0.20, "test_gap": 0.10}


def git_churn_recency(root, since=None):
    """One pass over `git log --name-only` -> {rel: churn}, {rel: last_touch_epoch}."""
    cmd = ["log", "--name-only", "--no-renames", "--pretty=format:\x01%ct"]
    if since:
        cmd.insert(1, f"--since={since}")
    out = run_git(root, cmd)
    if out is None:
        return None, None
    churn, last = {}, {}
    ts = None
    for line in out.splitlines():
        if line.startswith("\x01"):
            ts = int(line[1:]) if line[1:].isdigit() else ts
        elif line.strip():
            churn[line] = churn.get(line, 0) + 1
            if line not in last and ts:  # log is newest-first
                last[line] = ts
    return churn, last


def complexity_proxy(text):
    lines = text.splitlines()
    branches = sum(len(BRANCH_TOKENS.findall(ln)) for ln in lines)
    max_indent = 0
    for ln in lines:
        stripped = ln.lstrip(" \t")
        if not stripped:
            continue
        indent = len(ln) - len(stripped)
        max_indent = max(max_indent, indent)
    return branches + max_indent // 2 + len(lines) // 40


def cmd_hotspots(args):
    root = Path(args.root).resolve()
    churn, last_touch = git_churn_recency(root, args.since)
    use_git = churn is not None
    now = datetime.now(timezone.utc).timestamp()

    candidates = []
    test_stems = set()
    rows = []
    for p, rel in iter_files(root, args.exclude):
        lang = LANG_BY_EXT.get(p.suffix.lower())
        if not lang or lang not in CODE_LANGS:
            continue
        text = read_text(p)
        if text is None:
            continue
        first = "\n".join(text.splitlines()[:5])
        generated, vendored, tests = detect_flags(rel, text, first)
        if generated or vendored:
            continue
        if tests:
            test_stems.add(Path(rel).stem.replace(".test", "").replace(".spec", "")
                           .removeprefix("test_").removesuffix("_test").removesuffix("_spec"))
            continue
        rows.append((p, rel, text))

    for p, rel, text in rows:
        comp = complexity_proxy(text)
        boundary = 1 if (BOUNDARY_HINT.search(rel) or BOUNDARY_HINT.search(text[:4000])) else 0
        test_gap = 0 if Path(rel).stem in test_stems else 1
        if use_git:
            c = churn.get(rel, 0)
            recency_days = (now - last_touch.get(rel, 0)) / 86400 if rel in last_touch else None
        else:
            c = 0
            try:
                recency_days = (now - p.stat().st_mtime) / 86400
            except OSError:
                recency_days = None
        candidates.append({"path": rel, "churn": c, "complexity": comp,
                           "recency_days": round(recency_days, 1) if recency_days is not None else None,
                           "boundary": boundary, "test_gap": test_gap})

    max_churn = max((c["churn"] for c in candidates), default=0) or 1
    max_comp = max((c["complexity"] for c in candidates), default=0) or 1
    for c in candidates:
        recency_boost = 0.0
        if c["recency_days"] is not None:
            recency_boost = max(0.0, 1.0 - min(c["recency_days"], 365) / 365)
        score = (WEIGHTS["churn"] * (c["churn"] / max_churn)
                 + WEIGHTS["complexity"] * (c["complexity"] / max_comp)
                 + WEIGHTS["recency"] * recency_boost
                 + WEIGHTS["boundary"] * c["boundary"]
                 + WEIGHTS["test_gap"] * c["test_gap"])
        c["score"] = round(score, 4)
        reasons = []
        if c["churn"] >= max_churn * 0.5 and c["churn"] > 1:
            reasons.append(f"high churn ({c['churn']} commits)")
        if c["complexity"] >= max_comp * 0.5:
            reasons.append(f"complex (proxy {c['complexity']})")
        if recency_boost > 0.7:
            reasons.append("recently touched")
        if c["boundary"]:
            reasons.append("at a trust boundary")
        if c["test_gap"]:
            reasons.append("no matching test file")
        c["reasons"] = reasons

    candidates.sort(key=lambda c: -c["score"])
    emit({"gitAvailable": use_git, "weights": WEIGHTS,
          "hotspots": candidates[: args.top]})


