def main(argv=None):
    parser = argparse.ArgumentParser(prog="bughunt.py", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", default=".", help="repo root (default: cwd)")
    parser.add_argument("--quiet", action="store_true", help="suppress stderr progress")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("census", help="map languages, sizes, generated/vendored/tests")
    p.add_argument("--functions", action="store_true", help="emit pure-function candidates for /fuzz")
    p.add_argument("--exclude", nargs="*", default=[], help="extra ignore globs/prefixes")
    p.set_defaults(func=cmd_census)

    p = sub.add_parser("hotspots", help="rank files by likelihood-of-defect")
    p.add_argument("--top", type=int, default=20)
    p.add_argument("--since", default=None, help="churn window, e.g. '6 months ago'")
    p.add_argument("--exclude", nargs="*", default=[])
    p.set_defaults(func=cmd_hotspots)

    p = sub.add_parser("signals", help="pain-point pre-pass: TODO age, flags, config drift")
    p.add_argument("--max-age-days", type=int, default=180)
    p.add_argument("--exclude", nargs="*", default=[])
