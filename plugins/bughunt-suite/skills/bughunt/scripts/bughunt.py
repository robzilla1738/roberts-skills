#!/usr/bin/env python3
"""bughunt.py — zero-dependency toolkit for the bughunt skill (python3 stdlib only).

Deterministic pre-pass + findings pipeline:

    census    map the target: languages, sizes, generated/vendored/tests detection
    hotspots  rank files by likelihood-of-defect (churn x complexity x recency x boundary x test gap)
    signals   pain-point pre-pass: aged TODOs, feature flags, config drift, long scripts
    deps      manifest/lockfile audit: unpinned, no lockfile, lock drift, typosquat shape
    merge     validate + fingerprint + dedupe + suppress + baseline-diff findings JSON (CI gate)
    render    findings JSON -> markdown / HTML / SARIF 2.1.0 reports
    diff      fingerprint-compare two findings JSON files

All subcommands emit JSON to stdout (render writes files). Progress goes to stderr.
Exit codes (merge): 0 clean, 1 new Critical/High, 2 new Medium/Low. Usage/IO errors: 3.

The findings contract lives in schema/finding.schema.json next to this file; the
validator below is the executable version of it.
"""

