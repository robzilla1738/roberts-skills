def edit_distance_one(a, b):
    if a == b:
        return False
    la, lb = len(a), len(b)
    if abs(la - lb) > 1:
        return False
    if la == lb:  # substitution or adjacent transposition
        diffs = [i for i in range(la) if a[i] != b[i]]
        if len(diffs) == 1:
            return True
        return (len(diffs) == 2 and diffs[1] == diffs[0] + 1
                and a[diffs[0]] == b[diffs[1]] and a[diffs[1]] == b[diffs[0]])
    short, long_ = (a, b) if la < lb else (b, a)
    i = j = edits = 0
    while i < len(short) and j < len(long_):
        if short[i] != long_[j]:
            edits += 1
            if edits > 1:
                return False
            j += 1
        else:
            i += 1
            j += 1
    return True


def parse_npm(root, deps, ecosystems):
    pkg = root / "package.json"
    if not pkg.exists():
        return
    try:
        data = json.loads(pkg.read_text(errors="replace"))
    except json.JSONDecodeError:
        return
    lock = next((root / n for n in
                 ("package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb")
                 if (root / n).exists()), None)
    ecosystems.append({"manager": "npm", "manifest": "package.json",
                       "lockfile": lock.name if lock else None, "locked": lock is not None})
    locked_names = set()
    if lock and lock.name == "package-lock.json":
        try:
            lock_data = json.loads(lock.read_text(errors="replace"))
            for key in lock_data.get("packages", {}):
                if key.startswith("node_modules/"):
                    locked_names.add(key.split("node_modules/")[-1])
            locked_names.update(lock_data.get("dependencies", {}).keys())
        except json.JSONDecodeError:
            pass
    for section, direct in (("dependencies", True), ("devDependencies", True)):
        for name, ver in (data.get(section) or {}).items():
            issues = []
            if not EXACT_NPM.match(str(ver)):
                issues.append("UNPINNED")
            if lock is None:
                issues.append("NO_LOCKFILE")
            elif locked_names and name not in locked_names:
                issues.append("LOCK_DRIFT")
            if name in KNOWN_DEPRECATED:
                issues.append("DEPRECATED_MARKER")
            squat = next((p for p in POPULAR_PACKAGES if edit_distance_one(name, p)), None)
            if squat:
                issues.append("TYPOSQUAT_SHAPE")
            deps.append({"name": name, "version": str(ver), "manager": "npm",
                         "pinned": bool(EXACT_NPM.match(str(ver))), "direct": direct,
                         "issues": issues,
                         **({"typosquatOf": squat} if squat else {})})


PY_REQ = re.compile(r"^\s*([A-Za-z0-9_.\-]+)\s*(\[[^\]]*\])?\s*([=<>!~]{1,2}\s*[\w.*]+)?")


def parse_python(root, deps, ecosystems):
    req = root / "requirements.txt"
    pyproject = root / "pyproject.toml"
    manifest = req if req.exists() else (pyproject if pyproject.exists() else None)
    if manifest is None:
        return
    lock = next((root / n for n in ("poetry.lock", "uv.lock", "Pipfile.lock")
                 if (root / n).exists()), None)
    ecosystems.append({"manager": "pip", "manifest": manifest.name,
                       "lockfile": lock.name if lock else None, "locked": lock is not None})
    names = []
    if manifest is req:
        for line in req.read_text(errors="replace").splitlines():
            line = line.split("#")[0].strip()
            if not line or line.startswith("-"):
                continue
            m = PY_REQ.match(line)
            if m:
                names.append((m.group(1), m.group(3) or ""))
    else:
        in_deps = False
        for line in pyproject.read_text(errors="replace").splitlines():
            if re.match(r"\s*dependencies\s*=\s*\[", line):
                in_deps = True
                continue
            if in_deps:
                if "]" in line and "\"" not in line.split("]")[0]:
                    in_deps = False
                    continue
                for spec in re.findall(r'"([^"]+)"', line):
                    m = PY_REQ.match(spec)
                    if m:
                        names.append((m.group(1), m.group(3) or ""))
                if line.strip().endswith("]"):
                    in_deps = False
    for name, ver in names:
        pinned = ver.strip().startswith("==")
        issues = [] if pinned else ["UNPINNED"]
        if lock is None and manifest is not req:
            issues.append("NO_LOCKFILE")
        squat = next((p for p in POPULAR_PACKAGES if edit_distance_one(name.lower(), p)), None)
        if squat:
            issues.append("TYPOSQUAT_SHAPE")
        deps.append({"name": name, "version": ver.strip(), "manager": "pip",
                     "pinned": pinned, "direct": True, "issues": issues,
                     **({"typosquatOf": squat} if squat else {})})


def query_osv(deps, quiet):
    import urllib.request
    eco_map = {"npm": "npm", "pip": "PyPI"}
    queries = [{"package": {"name": d["name"], "ecosystem": eco_map[d["manager"]]},
                **({"version": d["version"]} if d.get("pinned") else {})}
               for d in deps if d["manager"] in eco_map]
    if not queries:
        return []
    body = json.dumps({"queries": queries}).encode()
    req = urllib.request.Request(
        "https://api.osv.dev/v1/querybatch", data=body,
        headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            results = json.loads(resp.read()).get("results", [])
    except Exception as e:  # fail-soft: offline checks still stand
        log(f"OSV query failed ({e}); continuing offline", quiet)
        return []
    advisories = []
    for d, res in zip([d for d in deps if d["manager"] in eco_map], results):
        for vuln in res.get("vulns", []) or []:
            advisories.append({"name": d["name"], "id": vuln.get("id"),
                               "severity": (vuln.get("database_specific") or {}).get("severity"),
                               "source": "osv.dev"})
    return advisories


