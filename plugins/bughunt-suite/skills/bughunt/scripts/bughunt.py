    p = sub.add_parser("deps", help="dependency audit (offline; --osv for advisories)")
    p.add_argument("--osv", action="store_true", help="query OSV.dev (network, opt-in)")
    p.set_defaults(func=cmd_deps)

    p = sub.add_parser("merge", help="validate+fingerprint+dedupe+suppress+baseline findings")
    p.add_argument("inputs", nargs="+", help="findings JSON files, or - for stdin")
    p.add_argument("--baseline", default=None, help=f"default: {STATE_DIR}/baseline.json")
    p.add_argument("--suppress", default=None, help=f"default: {STATE_DIR}/suppressions.json")
